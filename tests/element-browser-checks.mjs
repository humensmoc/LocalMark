import assert from "node:assert/strict";
import { join } from "node:path";
import { hoverTrackingChecks } from "./hover-browser-checks.mjs";

export async function elementChecks({ page, panel, context, base, out, until, ok, state }) {
  const consoleErrors = [];
  const onConsole = message => { if (message.type() === "error") consoleErrors.push(message.text()); };
  page.on("console", onConsole);
  await panel.textClick("当前页面");
  await page.goto(base + "/elements");
  await page.bringToFront();
  const host = page.locator("#local-web-clipper-root");
  async function expose() {
    await host.waitFor();
    const cdp = await context.newCDPSession(page), worlds = [];
    cdp.on("Runtime.executionContextCreated", ({ context }) => worlds.push(context));
    await cdp.send("Runtime.enable");
    const { root } = await cdp.send("DOM.getDocument", { depth: -1, pierce: true });
    const find = n => n.attributes?.includes("local-web-clipper-root") ? n : [...(n.children ?? []), ...(n.shadowRoots ?? [])].map(find).find(Boolean);
    for (const executionContextId of [undefined, worlds.find(w => w.name.includes("playwright"))?.id]) {
      const { object } = await cdp.send("DOM.resolveNode", { backendNodeId: find(root).shadowRoots[0].backendNodeId, executionContextId });
      await cdp.send("Runtime.callFunctionOn", { objectId: object.objectId,
        functionDeclaration: 'function(){const root=this;Object.defineProperty(this.host,"shadowRoot",{get:()=>root,configurable:true});}' });
    }
    await cdp.detach();
  }
  await expose();
  const savedPage = async () => Object.values((await state()).entries).find(e => e.page.url === base + "/elements")?.page;
  const marks = async () => (await savedPage())?.annotations ?? [];
  const count = async n => until(async () => (await marks()).length === n, "element annotation count " + n);
  const picker = host.locator(".element-picker"), editor = host.locator('.editor[data-state="open"]');
  const tooltip = host.locator('.tooltip[data-state="open"]');
  const toggle = host.locator(".element-pick-toggle");
  const eye = host.locator(".annotation-visibility-toggle");
  const start = async () => {
    await until(() => panel.evaluate(() => document.querySelector(".page-title-row h3")?.textContent === "元素标注测试"), "element page bridge");
    await toggle.click();
    await picker.waitFor();
    assert.equal(await toggle.getAttribute("aria-pressed"), "true");
  };
  const select = async selector => {
    await start();
    await page.locator(selector).click();
    await picker.waitFor({ state: "hidden" });
    await editor.waitFor();
  };
  const save = async note => {
    await editor.locator("#wc-note").fill(note);
    await editor.getByRole("button", { name: "保存", exact: true }).click();
    await editor.waitFor({ state: "hidden" });
  };
  await toggle.waitFor();
  assert.equal(await panel.evaluate(() => !!document.querySelector(".element-toolbar")), false);
  assert.equal(await toggle.textContent(), "");
  const checkEdge = async () => {
    const rect = await toggle.boundingBox(), viewport = await page.evaluate(() => ({ width: document.documentElement.clientWidth, height: innerHeight }));
    const eyeRect = await eye.boundingBox();
    assert.ok(eyeRect.y + eyeRect.height < rect.y && Math.abs(eyeRect.x - rect.x) <= 1, "eye is directly above the element button");
    assert.ok(Math.abs(rect.x + rect.width - viewport.width) <= 1, "icon touches the page right edge");
    assert.ok(Math.abs(rect.y + rect.height / 2 - viewport.height / 2) <= 1, "icon is vertically centered");
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  };
  await checkEdge();
  await page.screenshot({ path: join(out, "element-edge-button.png") });
  await panel.screenshot("element-sidebar-without-toolbar.png");
  for (const tab of ["最近网页", "标签", "当前页面"]) {
    await panel.textClick(tab);
    assert.equal(await toggle.isVisible(), true);
  }
  await start();
  await page.locator("#card-heading").hover();
  await toggle.click();
  await picker.waitFor({ state: "hidden" });
  assert.equal(await toggle.getAttribute("aria-pressed"), "false");
  await count(0);
  await start();
  await page.keyboard.press("Escape");
  await picker.waitFor({ state: "hidden" });
  assert.equal(await toggle.getAttribute("aria-pressed"), "false");
  await start();
  await panel.evaluate(() => document.querySelector(".tabs button").dispatchEvent(new KeyboardEvent("keydown", { key: "Escape", bubbles: true })));
  await picker.waitFor({ state: "hidden" });
  ok("icon-only page-edge toggle stays centered across sidebar tabs; repeat click and Escape from page or sidebar exit without saving");
  const original = await page.locator("#design-card").evaluate(el => ({ html: el.outerHTML, rect: el.getBoundingClientRect().toJSON() }));
  await start();
  await page.locator("#card-heading").hover();
  await until(async () => (await picker.locator(".element-picker-target").textContent()).includes("h2#card-heading"), "hover candidate");
  assert.equal(await picker.getByRole("button").count(), 0, "picker only shows the element and shortcut hints");
  assert.equal(await picker.locator(".element-picker-hints").textContent(), "↑ 父级↓ 子级Esc 退出左键添加批注");
  await page.keyboard.press("ArrowUp");
  assert.equal(await picker.locator(".element-picker-target").textContent(), "article#design-card");
  await page.keyboard.press("ArrowDown");
  assert.equal(await picker.locator(".element-picker-target").textContent(), "h2#card-heading");
  await page.keyboard.press("ArrowUp");
  assert.equal(await picker.locator(".element-picker-target").textContent(), "article#design-card");
  await page.screenshot({ path: join(out, "element-picker.png") });
  await page.locator("#card-heading").click();
  await picker.waitFor({ state: "hidden" });
  await editor.waitFor();
  await editor.locator("#wc-note").fill("整张卡片的批注");
  await editor.getByLabel("绿色", { exact: true }).click();
  await editor.waitFor({ state: "hidden" });
  await count(1);
  let elementMark = (await marks())[0];
  assert.equal(elementMark.anchor.kind, "element");
  assert.equal(elementMark.anchor.tag, "article", "left click keeps the ancestor selected with ArrowUp");
  assert.equal(elementMark.color, "green");
  assert.equal((await savedPage()).schemaVersion, 3);
  const outline = host.locator(`[data-element-mark="${elementMark.id}"]`);
  await outline.waitFor();
  const current = await page.locator("#design-card").evaluate(el => ({ html: el.outerHTML, rect: el.getBoundingClientRect().toJSON() }));
  assert.deepEqual(current, original);
  assert.equal(await outline.evaluate(el => getComputedStyle(el).borderStyle), "dashed");
  assert.equal(await outline.evaluate(el => getComputedStyle(el).pointerEvents), "none");
  await page.locator("#card-button").click();
  await page.locator("#card-link").click();
  assert.deepEqual(await page.evaluate(() => [window.buttonClicks, window.linkClicks]), [1, 1]);
  ok("compact picker shows only element and hints; arrow keys select parent/child and one left click opens its note, preserving source DOM/layout and original controls");

  await page.mouse.move(30, 110);
  await until(async () => await host.locator(".element-note-button").count() === 0, "element pencil hidden at rest");
  await page.screenshot({ path: join(out, "element-note-idle.png") });
  await page.locator("#card-heading").hover();
  await tooltip.waitFor();
  assert.equal(await tooltip.locator(`[data-hover-mark="${elementMark.id}"]`).textContent(), "整张卡片的批注");
  assert.equal(await tooltip.innerText(), "整张卡片的批注", "only the comment is shown, without a color label or placeholder");
  assert.equal(await tooltip.locator(".hover-note").evaluate(el => getComputedStyle(el).borderTopWidth), "0px");
  assert.equal(await tooltip.locator(".hover-quote").count(), 0, "element preview shows the comment without dumping source content");
  const pencil = outline.locator("button");
  await pencil.waitFor();
  assert.equal(await pencil.locator("svg").getAttribute("viewBox"), "0 0 24 24");
  await tooltip.evaluate(async el => { await Promise.all(el.getAnimations().map(a => a.finished)); });
  const pr = await pencil.boundingBox(), tr = await tooltip.boundingBox();
  assert.ok(pr.y + pr.height <= tr.y || tr.y + tr.height <= pr.y, "comment preview leaves the pencil uncovered");
  await page.screenshot({ path: join(out, "element-note-hover.png") });
  await tooltip.hover();
  await pencil.hover();
  assert.equal(await tooltip.isVisible(), true, "moving between comment and pencil keeps hover alive");
  assert.equal(await editor.isVisible(), false, "hovering the pencil does not open the editor");
  await pencil.click();
  await editor.waitFor();
  assert.equal(await editor.locator("#wc-note").inputValue(), "整张卡片的批注");
  await editor.getByRole("button", { name: "关闭编辑窗", exact: true }).click();
  await editor.waitFor({ state: "hidden" });
  await page.mouse.move(30, 110);
  await until(async () => await host.locator(".element-note-button").count() === 0, "leaving hides element pencil");
  await tooltip.waitFor({ state: "hidden" });
  await page.locator("#card-heading").hover();
  await pencil.waitFor();
  await toggle.hover();
  await until(async () => await host.locator(".element-note-button").count() === 0, "unrelated extension controls do not retain the pencil");
  await tooltip.waitFor({ state: "hidden" });
  await count(1);
  ok("saved element shows no idle icon; hover previews its comment and shared pencil; preview-to-pencil movement stays usable and clicking edits the existing mark");
  await hoverTrackingChecks({ page, host, target: page.locator("#card-heading"), out, name: "element" });
  ok("element comment tracks the pointer continuously in white rather than anchoring to its pencil");

  // Real text drag inside the element continues to use the shared selection composer.
  const box = await page.locator("#card-text").boundingBox();
  await page.mouse.move(box.x + 1, box.y + 13);
  await page.mouse.down();
  await page.mouse.move(box.x + Math.min(box.width - 2, 230), box.y + 13, { steps: 12 });
  await page.mouse.up();
  await host.locator(".editor .swatch").first().click();
  await count(2);
  assert.equal((await marks()).filter(m => m.anchor.kind !== "element").length, 1);
  await page.locator("#card-heading").hover();
  await outline.locator("button").click();
  await editor.locator("#wc-note").fill("修改后的元素批注");
  await editor.getByLabel("粉色", { exact: true }).click();
  await editor.waitFor({ state: "hidden" });
  await until(async () => (await marks()).find(m => m.id === elementMark.id)?.color === "pink", "element note edited");
  const imageBefore = await page.locator("#card-image").boundingBox();
  await select("#card-image");
  await save("图片自己的批注");
  await count(3);
  assert.equal((await marks()).filter(m => m.anchor.kind === "element").length, 2);
  assert.deepEqual(await page.locator("#card-image").boundingBox(), imageBefore);
  await page.locator("#card-image").hover();
  const imageMark = (await marks()).find(m => m.anchor.kind === "element" && m.anchor.tag === "img");
  await tooltip.locator(`[data-hover-mark="${imageMark.id}"]`).waitFor();
  assert.equal(await tooltip.locator(`[data-hover-mark="${imageMark.id}"]`).textContent(), "图片自己的批注");
  assert.equal(await tooltip.locator(`[data-hover-mark="${elementMark.id}"]`).textContent(), "修改后的元素批注");
  assert.equal(await host.locator(".element-note-button").count(), 2, "nested annotations each expose their own pencil");
  await page.screenshot({ path: join(out, "element-mixed-marks.png") });
  ok("nested image and card annotations coexist with real text highlighting; badge editing preserves IDs and text highlights");

  const imagePencil = host.locator(`[data-element-mark="${imageMark.id}"] button`);
  await imagePencil.click();
  await save("");
  await host.locator(".editor").waitFor({ state: "detached" });
  await page.locator("#card-image").hover();
  await until(async () => await tooltip.locator(`[data-hover-mark="${imageMark.id}"]`).textContent() === "无评论", "empty nested element note opens placeholder");
  assert.equal(await tooltip.locator(`[data-hover-mark="${elementMark.id}"]`).textContent(), "修改后的元素批注", "parent comment is preserved alongside the empty child");
  await tooltip.evaluate(async el => { await Promise.all(el.getAnimations().map(a => a.finished)); });
  await page.screenshot({ path: join(out, "element-empty-comment.png") });
  await imagePencil.click();
  await save("图片自己的批注");
  ok("empty element comments show 无评论 while nested parent comments remain readable and the pencil still edits");

  const storedMarks = await marks();
  const highlightCount = () => page.evaluate(() => [...CSS.highlights].filter(([name]) => name.startsWith("wc-")).reduce((n, [, ranges]) => n + ranges.size, 0));
  assert.ok(await highlightCount() > 0);
  await eye.click();
  await outline.waitFor({ state: "hidden" });
  await tooltip.waitFor({ state: "hidden" });
  assert.equal(await eye.getAttribute("aria-label"), "显示网页高亮和标注");
  assert.equal(await highlightCount(), 0);
  assert.equal(await host.locator(".rail").count(), 0);
  await page.locator("#card-heading").hover();
  assert.equal(await host.locator(".element-note-button").count(), 0);
  await page.evaluate(() => document.getElementById("design-card").setAttribute("data-visibility-check", "changed"));
  await page.waitForTimeout(400); // Allow the 250ms MutationObserver repaint to run.
  assert.equal(await highlightCount(), 0);
  assert.equal(await host.locator(".element-outline").count(), 0);
  await page.screenshot({ path: join(out, "page-annotations-hidden.png") });
  await eye.click();
  await outline.waitFor();
  assert.ok(await highlightCount() > 0);
  assert.deepEqual(await marks(), storedMarks, "visibility does not change saved marks");
  ok("eye hides text highlights, element frames, hover comments and rail; DOM repaint stays hidden, and showing restores unchanged marks");

  const settings = await context.newPage();
  const settingsConsole = [];
  settings.on("console", message => { if (message.type() === "error") settingsConsole.push(message.text()); });
  await settings.goto(await panel.evaluate(() => chrome.runtime.getURL("settings.html")));
  const setting = settings.getByRole("switch", { name: "显示元素选择按钮" });
  const eyeSetting = settings.getByRole("switch", { name: "显示高亮显隐按钮" });
  const sidebarSetting = settings.getByRole("switch", { name: "显示侧边栏按钮" });
  const sidebarButton = host.locator(".sidepanel-toggle");
  await until(async () => await setting.isEnabled(), "page tools setting ready");
  assert.equal(await setting.isChecked(), true);
  assert.equal(await eyeSetting.isChecked(), true);
  assert.equal(await sidebarSetting.isChecked(), true);
  await page.bringToFront();
  await eye.click();
  await start();
  await setting.click();
  await until(async () => !await setting.isChecked() && await setting.isEnabled(), "page tools disabled and saved");
  await toggle.waitFor({ state: "hidden" });
  assert.equal(await eye.isVisible(), true, "hiding the picker keeps the eye visible");
  assert.equal(await sidebarButton.isVisible(), true, "hiding the picker keeps the sidebar button visible");
  await eyeSetting.click();
  await until(async () => !await eyeSetting.isChecked() && await eyeSetting.isEnabled(), "eye setting saved");
  await eye.waitFor({ state: "hidden" });
  await picker.waitFor({ state: "hidden" });
  await outline.waitFor();
  assert.ok(await highlightCount() > 0, "disabling the tools restores annotations");
  await sidebarSetting.click();
  await until(async () => !await sidebarSetting.isChecked() && await sidebarSetting.isEnabled(), "sidebar setting saved");
  await sidebarButton.waitFor({ state: "hidden" });
  await page.reload();
  await expose();
  await outline.waitFor();
  assert.equal(await toggle.count(), 0, "disabled setting survives a page reload");
  await settings.reload();
  await until(async () => await setting.isEnabled(), "reloaded page tools setting ready");
  assert.equal(await setting.isChecked(), false);
  assert.equal(await eyeSetting.isChecked(), false);
  assert.equal(await sidebarSetting.isChecked(), false);
  await settings.bringToFront();
  await settings.screenshot({ path: join(out, "page-tools-settings.png") });
  await settings.setViewportSize({ width: 320, height: 850 });
  await settings.locator("#show-page-tool-element").scrollIntoViewIfNeeded();
  assert.equal(await settings.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  await settings.screenshot({ path: join(out, "page-tools-settings-narrow.png") });
  await setting.click();
  await until(async () => await setting.isChecked() && await setting.isEnabled(), "page tools enabled and saved");
  await toggle.waitFor();
  assert.equal(await eye.count(), 0);
  assert.equal(await sidebarButton.count(), 0);
  await eyeSetting.click();
  await until(async () => await eyeSetting.isChecked() && await eyeSetting.isEnabled(), "eye setting enabled");
  await eye.waitFor();
  await sidebarSetting.click();
  await until(async () => await sidebarSetting.isChecked() && await sidebarSetting.isEnabled(), "sidebar setting enabled");
  await sidebarButton.waitFor();
  await settings.screenshot({ path: join(out, "page-tools-settings-enabled-narrow.png") });
  assert.deepEqual(await marks(), storedMarks);
  assert.deepEqual(settingsConsole, []);
  await settings.close();
  await page.bringToFront();
  ok("three default-on settings independently hide/show page tools, cancel hidden picking and restore marks when hiding the eye; preferences survive reloads and fit 320px");

  await page.reload();
  await expose();
  await outline.waitFor();
  assert.equal((await marks()).find(m => m.id === elementMark.id)?.note, "修改后的元素批注");
  await page.evaluate(() => {
    const card = document.getElementById("design-card");
    const inserted = document.createElement("article");
    inserted.textContent = "前面新增的卡片";
    card.before(inserted);
  });
  await until(async () => {
    const a = await outline.boundingBox(), b = await page.locator("#design-card").boundingBox();
    return a && b && Math.abs(a.y - b.y) < 1;
  }, "outline follows moved card");
  await page.evaluate(() => { document.getElementById("card-heading").textContent = "节点被复用后的新卡片"; });
  await outline.waitFor({ state: "hidden" });
  await until(() => panel.evaluate(id => [...document.querySelectorAll(".card.current")].some(card => card.textContent.includes("修改后的元素批注") && card.textContent.includes("未定位")), elementMark.id), "unlocated shown");
  assert.equal((await marks()).find(m => m.id === elementMark.id)?.note, "修改后的元素批注");
  await panel.evaluate(() => {
    const card = [...document.querySelectorAll(".card.current")].find(el => el.textContent.includes("修改后的元素批注"));
    [...card.querySelectorAll("button")].find(b => b.textContent.includes("重新绑定")).click();
  });
  await picker.waitFor();
  await page.locator("#design-card").click({ position: { x: 8, y: 8 } });
  await editor.waitFor();
  assert.equal(await editor.locator("#wc-note").inputValue(), "修改后的元素批注");
  await save("重新绑定后保留的批注");
  await count(3);
  await outline.waitFor();
  assert.ok((await marks()).find(m => m.id === elementMark.id)?.anchor.text.includes("节点被复用"));
  ok("refresh restores marks; sibling insertions follow the same card; recycled content becomes unlocated and rebind preserves its ID/color/note");

  await start();
  await page.locator("#card-button").click({ button: "right" });
  assert.equal(await picker.isVisible(), true, "right click does not add a note");
  assert.equal(await editor.isVisible(), false);
  await page.locator("#card-button").click();
  await editor.waitFor();
  assert.equal(await page.evaluate(() => window.buttonClicks), 0, "selection consumes page button click");
  await page.keyboard.press("Escape");
  await editor.waitFor({ state: "hidden" });
  await page.locator("#card-button").click();
  assert.equal(await page.evaluate(() => window.buttonClicks), 1, "Escape restores native events");
  await select("#scroll-card");
  await save("滚动容器里的批注");
  await count(4);
  const scrollMark = (await marks()).find(m => m.note === "滚动容器里的批注");
  const scrollOutline = host.locator(`[data-element-mark="${scrollMark.id}"]`);
  await scrollOutline.waitFor();
  await page.locator("#scroller").evaluate(el => { el.scrollTop = el.scrollHeight; });
  await scrollOutline.waitFor({ state: "hidden" });
  await page.locator("#scroller").evaluate(el => { el.scrollTop = 90; });
  await scrollOutline.waitFor();
  const scroller = await page.locator("#scroller").boundingBox(), clipped = await scrollOutline.boundingBox();
  assert.ok(clipped.y >= scroller.y && clipped.y + clipped.height <= scroller.y + scroller.height + 1);
  ok("selection blocks page actions only while active; Escape cleans up; outlines respect nested scrolling and clipping");

  const metrics = await context.newCDPSession(page);
  await metrics.send("Emulation.setDeviceMetricsOverride", { width: 320, height: 600, deviceScaleFactor: 1, mobile: false });
  await page.evaluate(() => scrollTo(0, 0));
  await checkEdge();
  await start();
  await page.locator("#card-heading").hover();
  await until(async () => (await picker.locator(".element-picker-target").textContent()) === "h2#card-heading", "narrow picker candidate");
  await until(async () => { const r = await picker.boundingBox(); return r && r.x >= 0 && r.x + r.width <= 321; }, "narrow picker fits");
  assert.equal(await picker.evaluate(el => el.scrollWidth > el.clientWidth), false, "narrow hints do not overflow");
  await page.screenshot({ path: join(out, "element-picker-narrow.png") });
  await page.locator("#card-heading").click();
  await editor.waitFor();
  await editor.evaluate(async el => { await Promise.all(el.getAnimations().map(a => a.finished)); });
  if (await host.locator(".toast").isVisible()) await host.locator(".toast").click();
  const er = await editor.boundingBox();
  assert.ok(er.x >= 0 && er.x + er.width <= 321 && er.y + er.height <= 601);
  await page.screenshot({ path: join(out, "element-editor-narrow.png") });
  await editor.getByRole("button", { name: "关闭编辑窗", exact: true }).click();
  await editor.waitFor({ state: "hidden" });
  await page.locator("#card-image").hover();
  await tooltip.locator(`[data-hover-mark="${imageMark.id}"]`).waitFor();
  await tooltip.evaluate(async el => { await Promise.all(el.getAnimations().map(a => a.finished)); });
  const nr = await tooltip.boundingBox();
  assert.ok(nr.x >= 0 && nr.x + nr.width <= 321 && nr.y >= 0 && nr.y + nr.height <= 601, "narrow element comment fits viewport");
  assert.equal(await tooltip.evaluate(el => el.scrollWidth > el.clientWidth), false);
  await page.screenshot({ path: join(out, "element-note-hover-narrow.png") });
  await metrics.send("Emulation.clearDeviceMetricsOverride");
  await metrics.detach();
  await count(4);
  await until(async () => {
    const e = Object.values((await state()).entries).find(e => e.page.url === base + "/elements");
    return e && !e.dirty && !e.issue && JSON.parse(e.baseJson).annotations.length === 4;
  }, "element JSON persisted to OPFS");
  ok("320px picker/editor fit; cancelling creates no mark; v3 mixed annotations persist through the real file-sync pipeline");
  await page.locator("#card-image").scrollIntoViewIfNeeded();
  await page.locator("#card-image").hover();
  await host.locator(`[data-element-mark="${imageMark.id}"] button`).click();
  await editor.getByRole("button", { name: "删除", exact: true }).click();
  await count(3);
  await host.locator(`[data-element-mark="${imageMark.id}"]`).waitFor({ state: "hidden" });
  assert.equal((await marks()).filter(m => m.anchor.kind !== "element").length, 1);
  assert.ok((await marks()).some(m => m.id === elementMark.id));
  ok("deleting an image annotation removes only its own frame and note, preserving the enclosing card and text highlight");
  page.off("console", onConsole);
  assert.deepEqual(consoleErrors, [], "no element interaction console errors");
  return { expose };
}
